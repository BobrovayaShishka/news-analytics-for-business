"""Сохранённые страницы для проверки извлечения: по три на источник."""

from __future__ import annotations

from datetime import datetime, timezone


def _page(*, title: str, sentence: str, published: str, source_tail: str) -> str:
    return f"""<!DOCTYPE html>
<html lang="ru">
<head>
  <meta charset="utf-8">
  <title>{title} — {source_tail}</title>
  <meta property="article:published_time" content="{published}">
</head>
<body>
  <nav>Главная Новости Подписка</nav>
  <article>
    <h1>{title}</h1>
    <time datetime="{published}">дата</time>
    <p>{sentence}</p>
    <p>Денежно-кредитные условия остаются жёсткими, компании пересматривают планы займов и инвестиций на ближайший квартал.</p>
    <p class="caption">Фото: пресс-служба</p>
  </article>
  <aside>Читайте также: обзор соседней темы без фактов этой заметки</aside>
  <footer>Материал носит информационный характер</footer>
  <script>alert("не текст")</script>
</body>
</html>
"""


def _item(source: str, number: int, title: str, sentence: str, published: str, tail: str) -> dict:
    moment = datetime.fromisoformat(published).astimezone(timezone.utc).replace(microsecond=0)
    return {
        "id": f"{source}-{number}",
        "source": source,
        "title": title,
        "sentence": sentence,
        "published": moment,
        "html": _page(title=title, sentence=sentence, published=published, source_tail=tail),
    }


